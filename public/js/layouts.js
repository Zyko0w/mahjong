// Dispositions du plateau.
// Chaque forme est dessinée en ASCII, couche par couche : '#' = une tuile.
// Une case de la grille = une tuile. dx / dy décalent une couche d'une demi-tuile
// (valeur 1) pour l'effet « briques » des plateaux classiques.
// Coordonnées internes en demi-tuiles : une tuile occupe [x, x+2) × [y, y+2) sur la couche z.

function fromAscii(layers) {
  const p = [];
  layers.forEach((layer, z) => {
    const { rows, dx = 0, dy = 0 } = Array.isArray(layer) ? { rows: layer } : layer;
    rows.forEach((row, r) => {
      [...row].forEach((ch, c) => {
        if (ch === '#') p.push({ x: c * 2 + dx, y: r * 2 + dy, z });
      });
    });
  });
  return p;
}

function buildTurtle() {
  const p = [];
  const row = (r, c0, c1, z = 0) => {
    for (let c = c0; c <= c1; c++) p.push({ x: c * 2, y: r * 2, z });
  };
  row(0, 1, 12); row(1, 3, 10); row(2, 2, 11); row(3, 1, 12);
  row(4, 1, 12); row(5, 2, 11); row(6, 3, 10); row(7, 1, 12);
  p.push({ x: 0, y: 7, z: 0 }, { x: 26, y: 7, z: 0 }, { x: 28, y: 7, z: 0 });
  for (let r = 1; r <= 6; r++) row(r, 4, 9, 1);
  for (let r = 2; r <= 5; r++) row(r, 5, 8, 2);
  for (let r = 3; r <= 4; r++) row(r, 6, 7, 3);
  p.push({ x: 13, y: 7, z: 4 });
  return p; // 144
}

function buildExpress() {
  const p = [];
  for (let r = 0; r <= 4; r++) for (let c = 0; c <= 7; c++) p.push({ x: c * 2, y: r * 2, z: 0 });
  p.push({ x: -2, y: 4, z: 0 }, { x: 16, y: 4, z: 0 });
  for (let r = 1; r <= 3; r++) for (let c = 1; c <= 6; c++) p.push({ x: c * 2, y: r * 2, z: 1 });
  for (let c = 2; c <= 5; c++) p.push({ x: c * 2, y: 3, z: 2 }, { x: c * 2, y: 5, z: 2 });
  p.push({ x: 6, y: 4, z: 3 }, { x: 8, y: 4, z: 3 });
  return p; // 70
}

